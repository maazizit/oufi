export function t(lang: Lang, key: string, vars?: Record<string, string | number>) {
  let s = (T[key] && T[key][lang]) || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

export function L(lang: Lang, o?: Localized | string | null) {
  if (!o) return "";
  if (typeof o === "string") return o;
  return o[lang] || o.fr || "";
}

export function money(lang: Lang, n: number) {
  return `${new Intl.NumberFormat("fr-FR").format(Math.round(n))} ${t(lang, "dh")}`;
}
